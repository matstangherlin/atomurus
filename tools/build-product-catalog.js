#!/usr/bin/env node
/** Count live product surfaces so Home stats are not marketing guesses. */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

function read(rel) {
  return fs.readFileSync(path.join(ROOT, rel), 'utf8');
}

function listHtml(dir, { excludePt = true } = {}) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs).filter((name) => {
    if (!name.endsWith('.html')) return false;
    if (excludePt && name.endsWith('.pt.html')) return false;
    return true;
  });
}

function markupOnly(html) {
  return html
    .replace(/<script\b[\s\S]*?<\/script>/gi, '')
    .replace(/<style\b[\s\S]*?<\/style>/gi, '');
}

function uniqueAttr(html, attr) {
  const markup = markupOnly(html);
  const re = new RegExp(`\\s${attr}="([^"$]+)"`, 'g');
  const out = new Set();
  let m;
  while ((m = re.exec(markup))) out.add(m[1]);
  return [...out];
}

function countElements() {
  const preview = read('home-preview-data.js');
  const m = preview.match(/window\.HOME_PREVIEW_ELEMENTS = (\[[\s\S]*\]);/);
  if (!m) throw new Error('HOME_PREVIEW_ELEMENTS missing');
  return JSON.parse(m[1]).length;
}

function build() {
  const calculators = uniqueAttr(read('calculators.html'), 'data-target');
  const molecules = uniqueAttr(read('viewer/molecules.html'), 'data-mol');
  const atomicModels = listHtml('viewer/atomic-models');
  const articles = listHtml('explore');
  const isomerism = [
    ...listHtml('viewer/isomerism/constitutional'),
    ...listHtml('viewer/isomerism/spatial')
  ];
  const allotropeElements = uniqueAttr(read('viewer/allotropes.html'), 'data-elem');
  const elements = countElements();
  const catalog = {
    elements,
    calculators: calculators.length,
    molecules: molecules.length,
    atomicModels: atomicModels.length,
    articles: articles.length,
    isomerismTypes: isomerism.length,
    allotropeElements: allotropeElements.length,
    models: atomicModels.length + molecules.length
  };
  const js =
    '/* Auto-generated by tools/build-product-catalog.js — do not edit. */\n' +
    `window.ATOMURUS_CATALOG = ${JSON.stringify(catalog)};\n`;
  fs.writeFileSync(path.join(ROOT, 'assets', 'product-catalog.js'), js);
  console.log('Wrote assets/product-catalog.js', catalog);
  return catalog;
}

build();
