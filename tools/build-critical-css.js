#!/usr/bin/env node
/**
 * Build a small above-the-fold critical CSS slice from atomurus-lab-console.css.
 * Pages load this blocking, then the full lab-console stylesheet async.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'atomurus-lab-console.css');
const OUT = path.join(ROOT, 'assets', 'critical-lab.css');

const css = fs.readFileSync(SRC, 'utf8');

function sliceBetween(startNeedle, endNeedle) {
  const start = css.indexOf(startNeedle);
  if (start < 0) throw new Error(`Missing start marker: ${startNeedle}`);
  const end = endNeedle ? css.indexOf(endNeedle, start + startNeedle.length) : css.length;
  if (endNeedle && end < 0) throw new Error(`Missing end marker: ${endNeedle}`);
  return css.slice(start, endNeedle ? end : undefined).trim();
}

const parts = [
  '/* Auto-generated by tools/build-critical-css.js — do not edit by hand */',
  '/* Above-the-fold: tokens, body, data-strip, topnav, hero, doc-hero, mobile nav */',
  sliceBetween('.lc-sr-only {', '/* SIDEBAR */'),
  sliceBetween('/* DATA STRIP */', '/* PAGE HEADER */'),
  // Landing chrome through hero preview (stop before below-the-fold modules)
  sliceBetween('   LANDING PAGE (no sidebar — topnav + grid)', '.lc-modules {'),
  // Keep landing responsive rules for topnav/hero collapse
  sliceBetween('/* RESPONSIVE landing */', '/* ═════════════════════════════════════════\n   CALCULATORS UI'),
  // Doc shell + hero title (about/contact/privacy first paint)
  sliceBetween('.lc-doc {', '.lc-doc-desc {'),
  // Safe-area tokens + html background
  sliceBetween('/* Safe-area-inset tokens', '/* When running as installed PWA'),
];

const mobileNav = sliceBetween(
  '  /* Hide desktop nav controls on mobile',
  '  /* Keep lang + theme + CTA'
);

parts.push(`@media (max-width: 760px) {\n${mobileNav}\n}`);

// FOUC guard: hide <body> while the full design stylesheet (atomurus-lab-console.css)
// loads async. The class is set by scripts/fix-fouc-lab-css.js and removed on load.
const foucGuard = 'html.lc-loading body{visibility:hidden}\n';

let out = `*,*::before,*::after{box-sizing:border-box}\nhtml,body{margin:0}\n` +
  foucGuard +
  parts.filter(Boolean).join('\n\n') + '\n';

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out, 'utf8');
console.log(`Wrote ${path.relative(ROOT, OUT)} (${out.length} bytes)`);
