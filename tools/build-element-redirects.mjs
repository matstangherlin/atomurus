// /element/<number | PT name | EN name> → /periodic-table/<latin slug> (prompt 26, B03).
//
//   node tools/build-element-redirects.mjs           → rewrite the block in netlify.toml
//   node tools/build-element-redirects.mjs --check   → exit 1 if the block is missing or stale
//
// Built from elements-data.js (ELEMENTS, _elNamesEN, ELEMENT_LATIN), between
// «# BEGIN element-redirects» and «# END element-redirects». 301s:
//   /element/26     → /periodic-table/ferrum           (language-neutral; the page follows the visitor's language)
//   /element/ferro  → /periodic-table/ferrum           (PT name: the PT page is the default)
//   /element/iron   → /periodic-table/ferrum?lang=en   (EN name: the EN variant, as prompt 12 serves it)
// Names are lower-case ASCII (accents dropped, spaces → hyphens). Anything else
// under /element/ (e.g. /element/999) stays a real 404: no /element/* catch-all.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TOML = path.join(ROOT, 'netlify.toml');
export const BEGIN = '# BEGIN element-redirects (generated by tools/build-element-redirects.mjs — do not edit by hand)';
export const END = '# END element-redirects';
const ANCHOR = '# Hide .html in URL bar';

export function loadElements() {
  const ctx = { window: {} };
  vm.createContext(ctx);
  vm.runInContext(fs.readFileSync(path.join(ROOT, 'elements-data.js'), 'utf8') + ';this.__E = { ELEMENTS, _elNamesEN, ELEMENT_LATIN };', ctx);
  return ctx.__E;
}

export function slugName(name) {
  return String(name).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
}

export function buildRules() {
  const { ELEMENTS, _elNamesEN, ELEMENT_LATIN } = loadElements();
  const rules = [];
  const seen = new Map();
  const skipped = [];
  const add = (from, to) => {
    if (seen.has(from)) {
      if (seen.get(from) !== to) skipped.push(`${from}: ${seen.get(from)} vs ${to}`);
      return;
    }
    seen.set(from, to);
    rules.push({ from, to });
  };
  const sorted = ELEMENTS.slice().sort((a, b) => a.z - b.z);
  for (const el of sorted) add(`/element/${el.z}`, `/periodic-table/${ELEMENT_LATIN[el.z]}`);
  for (const el of sorted) add(`/element/${slugName(el.name)}`, `/periodic-table/${ELEMENT_LATIN[el.z]}`);
  for (const el of sorted) add(`/element/${slugName(_elNamesEN[el.z - 1])}`, `/periodic-table/${ELEMENT_LATIN[el.z]}?lang=en`);
  return { rules, skipped };
}

export function renderBlock(rules) {
  const lines = [BEGIN, `# ${rules.length} rules: /element/<Z>, /element/<PT name>, /element/<EN name>.`];
  for (const r of rules) {
    lines.push('[[redirects]]', `  from   = "${r.from}"`, `  to     = "${r.to}"`, '  status = 301', '  force  = true', '');
  }
  lines.push(END);
  return lines.join('\n');
}

export function currentBlock(toml) {
  const a = toml.indexOf(BEGIN);
  const b = toml.indexOf(END);
  if (a === -1 || b === -1 || b < a) return null;
  return toml.slice(a, b + END.length);
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { rules, skipped } = buildRules();
  const block = renderBlock(rules);
  const toml = fs.readFileSync(TOML, 'utf8');
  const existing = currentBlock(toml);
  if (process.argv.includes('--check')) {
    if (existing !== block) {
      console.error('build-element-redirects: the block in netlify.toml is ' + (existing ? 'stale' : 'missing') + ' — run node tools/build-element-redirects.mjs');
      process.exit(1);
    }
    console.log(`build-element-redirects: ok (${rules.length} rules)`);
  } else {
    let next;
    if (existing) next = toml.replace(existing, block);
    else {
      const at = toml.indexOf(ANCHOR);
      if (at === -1) throw new Error('anchor not found in netlify.toml: ' + ANCHOR);
      next = toml.slice(0, at) + '# Short element URLs (prompt 26): /element/26, /element/ferro, /element/iron.\n' + block + '\n\n' + toml.slice(at);
    }
    fs.writeFileSync(TOML, next);
    console.log(`build-element-redirects: wrote ${rules.length} rules${skipped.length ? ' (skipped ' + skipped.length + ' conflicting names: ' + skipped.join('; ') + ')' : ''}`);
  }
}
