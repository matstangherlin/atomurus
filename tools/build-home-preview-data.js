const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = path.join(ROOT, 'elements-data.js');
const OUT = path.join(ROOT, 'home-preview-data.js');

function extractLiteral(code, declMarker) {
  const start = code.indexOf(declMarker);
  if (start < 0) return null;
  let i = start + declMarker.length;
  while (i < code.length && code[i] !== '{' && code[i] !== '[') i++;
  if (i >= code.length) return null;
  const open = code[i];
  const close = open === '{' ? '}' : ']';
  const litStart = i;
  let depth = 0;
  let s = 0; // 0=code, 1=', 2=", 3=`, 4=//, 5=/* */
  for (; i < code.length; i++) {
    const c = code[i];
    const n = code[i + 1];
    if (s === 4) { if (c === '\n') s = 0; continue; }
    if (s === 5) { if (c === '*' && n === '/') { s = 0; i++; } continue; }
    if (s === 1) { if (c === '\\') { i++; continue; } if (c === "'") s = 0; continue; }
    if (s === 2) { if (c === '\\') { i++; continue; } if (c === '"') s = 0; continue; }
    if (s === 3) { if (c === '\\') { i++; continue; } if (c === '`') s = 0; continue; }
    if (c === '/' && n === '/') { s = 4; i++; continue; }
    if (c === '/' && n === '*') { s = 5; i++; continue; }
    if (c === "'") { s = 1; continue; }
    if (c === '"') { s = 2; continue; }
    if (c === '`') { s = 3; continue; }
    if (c === open) depth++;
    else if (c === close) {
      depth--;
      if (depth === 0) return code.slice(litStart, i + 1);
    }
  }
  return null;
}

function loadElements() {
  const code = fs.readFileSync(SOURCE, 'utf8');
  const literal = extractLiteral(code, 'const ELEMENTS = ');
  if (!literal) throw new Error('ELEMENTS literal not found in elements-data.js');
  // eslint-disable-next-line no-eval
  return eval('(' + literal + ')');
}

function buildPreviewData(elements) {
  return elements.map((el) => ({
    z: el.z,
    sym: el.sym,
    name: el.name,
    cat: el.cat,
    col: el.col,
    row: el.row,
  }));
}

function main() {
  const preview = buildPreviewData(loadElements());
  const output =
    '// Auto-generated by tools/build-home-preview-data.js\n' +
    `window.HOME_PREVIEW_ELEMENTS = ${JSON.stringify(preview)};\n`;
  fs.writeFileSync(OUT, output, 'utf8');
  console.log(`Generated home preview payload with ${preview.length} elements`);
}

main();
