// Physical constants from one source (prompt 29, B05).
//
//   node tools/build-physical-constants.mjs           → write the two generated copies
//   node tools/build-physical-constants.mjs --check   → exit 1 if either is missing or stale
//
// assets/data/physical-constants.json → assets/data/physical-constants.js
// (classic script / CommonJS: window.AtomurusConstants, require()) and
// netlify/lib/physical-constants.mjs (ESM, for the Netlify Functions). Derived
// constants (R = N_A·k_B, F = N_A·e, Torr, mmHg) are computed here, so no copy
// ever carries a typed rounding of them.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'assets', 'data', 'physical-constants.json');
export const OUT_BROWSER = path.join(ROOT, 'assets', 'data', 'physical-constants.js');
export const OUT_ESM = path.join(ROOT, 'netlify', 'lib', 'physical-constants.mjs');

export function resolveConstants(source = JSON.parse(fs.readFileSync(SRC, 'utf8'))) {
  const defs = source.constants;
  const values = {};
  const pending = Object.keys(defs);
  for (let guard = 0; pending.length && guard < 10; guard += 1) {
    for (let i = pending.length - 1; i >= 0; i -= 1) {
      const key = pending[i];
      const def = defs[key];
      if ('value' in def) {
        values[key] = def.value;
        pending.splice(i, 1);
        continue;
      }
      const names = def.derived.match(/[A-Za-z_][A-Za-z_0-9]*/g) || [];
      if (!names.every((n) => n in values)) continue;
      // Only + − × ÷, numbers and constants already resolved.
      if (!/^[\sA-Za-z_0-9.*/+\-()]+$/.test(def.derived)) throw new Error('bad expression for ' + key);
      values[key] = Function(...Object.keys(values), `return (${def.derived});`)(...Object.values(values));
      pending.splice(i, 1);
    }
  }
  if (pending.length) throw new Error('unresolved constants: ' + pending.join(', '));
  return { values, defs };
}

function header(kind) {
  return `/* Generated by tools/build-physical-constants.mjs from assets/data/physical-constants.json (${kind}). Do not edit. */\n`;
}

export function render() {
  const { values, defs } = resolveConstants();
  const keys = Object.keys(defs);
  const sources = Object.fromEntries(keys.map((k) => [k, { unit: defs[k].unit, exact: Boolean(defs[k].exact), source: defs[k].source }]));
  const body = keys.map((k) => `  ${k}: ${JSON.stringify(values[k])}`).join(',\n');
  const browser = header('classic script / CommonJS') +
    '(function (root) {\n' +
    "  'use strict';\n" +
    '  var C = {\n' + body.replace(/^/gm, '  ') + ',\n    SOURCES: ' + JSON.stringify(sources) + '\n  };\n' +
    '  C = Object.freeze(C);\n' +
    '  root.AtomurusConstants = C;\n' +
    "  if (typeof module === 'object' && module.exports) module.exports = C;\n" +
    "})(typeof globalThis !== 'undefined' ? globalThis : this);\n";
  const esm = header('ES module') +
    keys.map((k) => `export const ${k} = ${JSON.stringify(values[k])};`).join('\n') + '\n' +
    'export const SOURCES = Object.freeze(' + JSON.stringify(sources) + ');\n' +
    'export default Object.freeze({ ' + keys.join(', ') + ', SOURCES });\n';
  return { browser, esm };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { browser, esm } = render();
  if (process.argv.includes('--check')) {
    const stale = [[OUT_BROWSER, browser], [OUT_ESM, esm]]
      .filter(([file, text]) => !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text)
      .map(([file]) => path.relative(ROOT, file));
    if (stale.length) {
      console.error('build-physical-constants: stale ' + stale.join(', ') + ' — run node tools/build-physical-constants.mjs');
      process.exit(1);
    }
    console.log('build-physical-constants: ok');
  } else {
    fs.writeFileSync(OUT_BROWSER, browser);
    fs.writeFileSync(OUT_ESM, esm);
    console.log('build-physical-constants: wrote ' + [OUT_BROWSER, OUT_ESM].map((f) => path.relative(ROOT, f)).join(', '));
  }
}
