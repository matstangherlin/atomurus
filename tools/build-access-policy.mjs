#!/usr/bin/env node
// assets/access-policy.js is the browser copy of netlify/lib/feature-catalog.mjs
// (prompt 34): one source for the server and the browser. It carries the
// access after the owner's switches (FREE_TIER_OVERRIDES), the page routes the
// presentation gate uses, and the school-plan flag the pricing page reads.
//
//   node tools/build-access-policy.mjs          → write assets/access-policy.js
//   node tools/build-access-policy.mjs --check  → exit 1 if it is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACCESS_CONFIG, PAGE_TOOL_ROUTES, accessCatalog, resolveAccessConfig } from '../netlify/lib/feature-catalog.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'assets', 'access-policy.js');

const q = (s) => "'" + String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const val = (v) => (v === null ? 'null' : q(v));
const table = (name, rows, fields) => '  var ' + name + ' = {\n' +
  Object.entries(rows).map(([k, spec]) => '    ' + k + ': { ' + fields.map((f) => f + ': ' + val(spec[f])).join(', ') + ' }').join(',\n') + '\n  };\n';

export function renderAccessPolicy(config = ACCESS_CONFIG) {
  const cat = accessCatalog(config);
  const { schoolEnabled } = resolveAccessConfig(config);
  const routes = PAGE_TOOL_ROUTES.map((r) => '    { tool: ' + q(r.tool) + ', kind: ' + q(r.kind) + ', patterns: [' + r.patterns.map(q).join(', ') + '] }').join(',\n');
  return '/* Atomurus access-model V2 — browser copy of netlify/lib/feature-catalog.mjs.\n' +
    '   Generated by tools/build-access-policy.mjs — do not edit; change the catalog and rebuild.\n' +
    '   tools/test-feature-catalog.mjs compares the two. */\n' +
    '(function (root) {\n  \'use strict\';\n\n' +
    table('FEATURES', cat.FEATURES, ['access', 'category']) + '\n' +
    table('LAB_TABS', cat.LAB_TABS, ['access', 'feature']) + '\n' +
    table('PAGE_TOOLS', cat.PAGE_TOOLS, ['access', 'feature']) + '\n' +
    '  /* Which page is which tool, tested in order; /explore/ pages are always public. */\n' +
    '  var PAGE_TOOL_ROUTES = [\n' + routes + '\n  ];\n\n' +
    '  root.ATOMURUS_ACCESS = {\n' +
    '    FEATURES: FEATURES,\n    LAB_TABS: LAB_TABS,\n    PAGE_TOOLS: PAGE_TOOLS,\n    PAGE_TOOL_ROUTES: PAGE_TOOL_ROUTES,\n' +
    '    SCHOOL_PLAN_ENABLED: ' + String(schoolEnabled) + ',\n' +
    '    featureAccess: function (featureKey) {\n      var spec = FEATURES[featureKey];\n      return spec ? spec.access : \'pro\';\n    }\n  };\n' +
    '  // The gate may have loaded first (both scripts are injected): tell it the catalog is here.\n' +
    '  if (typeof document !== \'undefined\' && document.dispatchEvent && typeof Event === \'function\') {\n' +
    '    document.dispatchEvent(new Event(\'atomurus-access-ready\'));\n  }\n' +
    '})(typeof window !== \'undefined\' ? window : this);\n';
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const js = renderAccessPolicy();
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== js) {
      console.error('build-access-policy: assets/access-policy.js is stale — run node tools/build-access-policy.mjs');
      process.exit(1);
    }
    console.log('build-access-policy: ok');
  } else {
    fs.writeFileSync(OUT, js);
    console.log('build-access-policy: wrote assets/access-policy.js');
  }
}
