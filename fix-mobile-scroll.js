// ───────────────────────────────────────────────────────────────────
// Atomurus — one-time migration: fix mobile scroll lock
// ───────────────────────────────────────────────────────────────────
// 118 element pages and 5 atomic-model pages share the same inline CSS:
//
//   html, body { height: 100vh; overflow: hidden; }       /* desktop */
//   @media (max-width: 760px) {
//     body { display: block; height: auto; overflow: auto; }  /* mobile */
//   }
//
// The mobile rule only overrides `body`, leaving `html` with
// `overflow: hidden`. Browsers treat <html> as the root scrolling
// container, so the whole page is frozen on mobile — users can't
// scroll past the first screen.
//
// Fix: include `html` in the mobile reset. Idempotent.
// ───────────────────────────────────────────────────────────────────

'use strict';

const fs   = require('fs');
const path = require('path');

const ROOT = __dirname;

// Target files: element pages + atomic-model pages. Skip generated
// .en.html / .pt.html variants (they're regenerated by build-i18n.js
// after the source is fixed).
const TARGETS = [];

function collect(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isFile() && entry.name.endsWith('.html') &&
        !entry.name.endsWith('.en.html') &&
        !entry.name.endsWith('.pt.html')) {
      TARGETS.push(path.join(dir, entry.name));
    }
  }
}
collect(path.join(ROOT, 'periodic-table'));
collect(path.join(ROOT, 'viewer', 'atomic-models'));

let fixed = 0, skipped = 0;

for (const file of TARGETS) {
  let html = fs.readFileSync(file, 'utf8');

  // Skip if already migrated.
  if (/html,\s*body\s*\{\s*display:\s*block;\s*height:\s*auto;\s*overflow:\s*auto;\s*\}/.test(html)) {
    skipped++;
    continue;
  }

  // Pattern: `body { display: block; height: auto; overflow: auto; }`
  // appears INSIDE the @media block. The rule lives in inline <style>,
  // sometimes multi-line, sometimes single-line. Match by content.
  const before = html;
  html = html.replace(
    /body\s*\{\s*display:\s*block;\s*height:\s*auto;\s*overflow:\s*auto;\s*\}/,
    'html, body { display: block; height: auto; overflow: auto; }'
  );

  if (html === before) {
    console.warn(`  no anchor: ${path.relative(ROOT, file).replace(/\\/g, '/')}`);
    skipped++;
    continue;
  }

  fs.writeFileSync(file, html, 'utf8');
  fixed++;
}

console.log(`Fixed: ${fixed}`);
console.log(`Skipped: ${skipped}`);
console.log(`Total targets: ${TARGETS.length}`);
